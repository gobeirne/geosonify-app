  function sep(ra1, dec1, ra2, dec2) {
    var dp = (dec2 - dec1) * D2R, dl = (ra2 - ra1) * D2R;
    var a = Math.sin(dp / 2) * Math.sin(dp / 2) +
            Math.cos(dec1 * D2R) * Math.cos(dec2 * D2R) * Math.sin(dl / 2) * Math.sin(dl / 2);
    return 2 * Math.asin(Math.min(1, Math.sqrt(a))) / D2R;      // degrees
  }

  function entry(s, d) {
    return { ra: s[0], dec: s[1], mag: s[2], name: s[3], con: s[4],
             distLy: (s[5] === undefined ? null : s[5]), sepDeg: d };
  }

  /*
    Stars within radiusDeg of one direction, nearest first.
    opts.maxMag caps faintness; opts.limit caps the result count.
  */
  function near(raDeg, decDeg, radiusDeg, opts) {
    opts = opts || {};
    var maxMag = opts.maxMag === undefined ? 99 : opts.maxMag;
    var out = [];
    for (var i = 0; i < STARS.length; i++) {
      var s = STARS[i];
      if (s[2] > maxMag) continue;
      // Cheap declination reject before the trig: no star further than
      // radiusDeg in declination can be within radiusDeg on the sphere.
      if (Math.abs(s[1] - decDeg) > radiusDeg) continue;
      var d = sep(raDeg, decDeg, s[0], s[1]);
      if (d <= radiusDeg) out.push(entry(s, d));
    }
    out.sort(function (a, b) { return a.sepDeg - b.sepDeg; });
    return opts.limit ? out.slice(0, opts.limit) : out;
  }

  /*
    Stars near a TRACK: minimum separation to any vertex, nearest first.

    Vertex-wise rather than perpendicular-to-segment. For a commute the vertices
    are metres apart on the sky while the separations reported are degrees, so
    the difference is far below anything quoted. Densify the track first if that
    ever stops being true.

    vertices: [[dec, ra], ...] -- the order GeosonifySkyFigures.toPaths() uses
    and GeosonifySkyOverlay.projectRing expects.
  */
  function nearTrack(vertices, radiusDeg, opts) {
    opts = opts || {};
    var maxMag = opts.maxMag === undefined ? 99 : opts.maxMag;
    var best = new Map();

    for (var v = 0; v < vertices.length; v++) {
      var dec = vertices[v][0], ra = vertices[v][1];
      for (var i = 0; i < STARS.length; i++) {
        var s = STARS[i];
        if (s[2] > maxMag) continue;
        if (Math.abs(s[1] - dec) > radiusDeg) continue;
        var d = sep(ra, dec, s[0], s[1]);
        if (d > radiusDeg) continue;
        var prev = best.get(i);
        if (prev === undefined || d < prev) best.set(i, d);
      }
    }

    var out = [];
    best.forEach(function (d, i) { out.push(entry(STARS[i], d)); });
    out.sort(function (a, b) { return a.sepDeg - b.sepDeg; });
    return opts.limit ? out.slice(0, opts.limit) : out;
  }

  /*
    The nearest star at any distance, by widening the search rather than
    scanning the whole catalogue at full trig cost. Always returns something:
    the sky has no empty directions at this depth.
  */
  function nearest(raDeg, decDeg, opts) {
    opts = opts || {};
    var r = opts.startDeg || 2;
    for (var i = 0; i < 8; i++) {
      var hit = near(raDeg, decDeg, r, { maxMag: opts.maxMag, limit: 1 });
      if (hit.length) return hit[0];
      r *= 2;
      if (r > 180) break;
    }
    return null;
  }

  function formatSep(deg) {
    if (deg >= 1) return deg.toFixed(2) + '\u00b0';
    if (deg >= 1 / 60) return (deg * 60).toFixed(1) + '\u2032';
    return (deg * 3600).toFixed(1) + '\u2033';
  }

