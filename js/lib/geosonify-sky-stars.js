/*
  geosonify-sky-stars.js  — bright-star catalogue + cone / path search

  WHY THIS EXISTS, AND WHAT IT HONESTLY CAN AND CANNOT ANSWER
  ----------------------------------------------------------
  "Which stars does my commute pass?" is a lovely question with an awkward
  arithmetic answer, and it is better to know the arithmetic up front than to
  ship something that silently returns nothing.

  A commute maps to the sky through the same identity the rest of sky mode uses:
  latitude -> declination, longitude -> right ascension. So the patch it sweeps
  is exactly as large as the commute is in degrees, and commutes are small:

      central London, 12 km E-W    0.020 x 0.170 deg   =  0.0034 deg^2
      Christchurch, 8 km           0.030 x 0.090 deg   =  0.0027 deg^2
      a 40 km LA freeway run       0.150 x 0.350 deg   =  0.0525 deg^2

  Against a naked-eye sky of 8,920 stars to magnitude 6.5, the density is
  0.216 stars per square degree. The expected count INSIDE a London commute is
  therefore 0.0007 stars. Not "usually none" -- essentially never.

  So a containment test is the wrong question. This module answers the right one:
  what is NEAR the track, and how near. Typical nearest-neighbour distances,
  0.5/sqrt(density):

      mag <= 3    7.6 deg        mag <= 5    2.5 deg
      mag <= 4    4.4 deg        mag <= 6.5  1.1 deg

  A commute will usually have a catalogued star within a degree or two, and a
  named one within several. That is a real, checkable, satisfying answer. "You
  pass 0.4 deg from Alnilam" is true; "your commute contains Alnilam" would not
  be.

  THE DATA
  --------
  Derived from the HYG database v3.8 (astronexus/HYG-Database), itself compiled
  from Hipparcos, Yale Bright Star and Gliese -- all public domain. Selection:
  every star with a proper name or Bayer/Flamsteed designation, plus everything
  to magnitude 5.0. 1,765 entries.

  Cross-checked against the eleven stars hand-entered in geosonify-sky-figures.js
  from published sexagesimal: all eleven agree to under 1 arcsecond (worst 0.8",
  Alnitak). Two independent transcriptions of the same sky.

  Positions are J2000 / ICRS, matching the frame tag sky mode emits. Proper
  motion is NOT applied: over 26 years from J2000 even Barnard's Star moves ~4.7
  arcmin, and every other star far less -- immaterial against separations quoted
  in degrees, and applying it would imply a precision this catalogue's 4-decimal
  storage does not carry.

  SEPARATIONS USE HAVERSINE, NEVER ARCCOS
  ---------------------------------------
  arccos has a precision floor of sqrt(epsilon) ~ 0.003 arcsec, coarser than a
  HEALPix cell above order 22. This bit the project three times in one session.

  Format: [raDeg, decDeg, mag, label, constellation, distanceLightYears]

  Distance is null where HYG carries no usable parallax (30 of 1,765). HYG
  stores 100000 pc as the sentinel for that; passing it through as a number
  would report every unmeasured star as 326,156 light years away, which is
  outside the Galaxy and would look like data rather than absence.
*/
