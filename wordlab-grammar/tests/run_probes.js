'use strict';
// Runs the intended-analysis probes; writes reports/probe_analyses.md and
// returns {pass, fail} for CI. Usage: node tests/run_probes.js
const fs = require('fs'), path = require('path');
const {load} = require('../src/load');
const engine = load();
const P = JSON.parse(fs.readFileSync(path.join(__dirname, 'probes.json'), 'utf8')).probes;

function tilesOf(p) { return p.tiles ? p.tiles.map(([word, source]) => ({word, source})) : p.text; }
function words(p) { return p.tiles ? p.tiles.map(t => t[0]) : p.text.toLowerCase().replace(/[.,;:!?]/g, ' ').split(/\s+/).filter(Boolean); }
function indexOfKey(ws, key) {
  const [w, n] = key.split('#'); let c = 0;
  for (let i = 0; i < ws.length; i++) if (ws[i] === w && ++c === (Number(n) || 1)) return i;
  return -1;
}
function checkRoles(reading, ws, roles) {
  const bad = [];
  for (const [k, want] of Object.entries(roles || {})) {
    const i = indexOfKey(ws, k);
    if (i < 0) { bad.push(k + ': word not in sentence'); continue; }
    const got = reading.roles[i].pos + ':' + reading.roles[i].role;
    const ok = Array.isArray(want) ? want.includes(got) : got === want;
    if (!ok) bad.push(k + ': got ' + got + ', want ' + (Array.isArray(want) ? want.join('|') : want));
  }
  return bad;
}
function readingOk(r, p, ws) {
  const e = p.expect, bad = [];
  if (e.type && r.utteranceType !== e.type) bad.push('type ' + r.utteranceType + ' != ' + e.type);
  for (const f of e.families || []) if (!r.families.includes(f)) bad.push('missing family ' + f);
  return bad.concat(checkRoles(r, ws, e.roles));
}

function runProbe(p) {
  const ws = words(p);
  let pins;
  if (p.pins) { pins = {}; for (const [k, pos] of Object.entries(p.pins)) pins[indexOfKey(ws, k)] = pos; }
  const res = engine.parse(tilesOf(p), {pins});
  const e = p.expect;
  let failures = [];
  if (e.state === 'not_recognised') { if (res.state === 'recognised') failures.push('recognised, expected not'); }
  else if (res.state !== e.state) failures.push('state ' + res.state + ' != ' + e.state + (res.reason ? ' (' + res.reason + ')' : ''));
  if (!failures.length && e.state === 'conflict' && !res.conflicts.some(c => c.constraint === e.conflict)) failures.push('conflict ' + res.conflicts.map(c => c.constraint).join('+') + ' lacks ' + e.conflict);
  if (!failures.length && e.state === 'recognised') {
    if ((e.where || 'canonical') === 'canonical' || e.where === 'pinned') failures = readingOk(res.canonical, p, ws);
    else { const tries = res.readings.map(r => readingOk(r, p, ws)); if (!tries.some(t => !t.length)) failures = ['no offered reading matches; closest: ' + tries.sort((a, b) => a.length - b.length)[0].join('; ')]; }
  }
  return {p, res, ws, failures};
}

function fmtRoles(r) { return r.roles.map(x => x.word + '/' + x.pos + ':' + x.role + (x.tier && x.tier !== 'curated' ? '(' + x.tier + ')' : '')).join(' '); }

function main() {
  const out = [], md = ['# Phase 0 probe analyses', '', 'Generated by `node tests/run_probes.js`. Each probe states the intended analysis (from the handover) as role assertions. Roles are `word/POS:function`; non-curated lexical evidence tiers are shown in brackets. "Canonical" is the preference-model choice, which never consults a score.', ''];
  let pass = 0, fail = 0;
  for (const p of P) {
    const r = runProbe(p); out.push(r);
    const ok = !r.failures.length; ok ? pass++ : fail++;
    md.push('## ' + p.id + ' — ' + (ok ? 'PASS' : 'FAIL') + ' (' + p.src + ')', '', '`' + (p.text || p.tiles.map(t => t[0] + (t[1] === 'helper' ? '[gold]' : '[blue]')).join(' ')) + '`' + (p.pins ? '  — pinned: ' + JSON.stringify(p.pins) : ''), '');
    const res = r.res;
    md.push('State: **' + res.state + '**' + (res.treeCount ? ' · ' + res.treeCount + ' complete trees · ' + res.readings.length + ' offered readings' : '') + (res.ms !== undefined ? ' · ' + res.ms.toFixed(1) + ' ms' : ''), '');
    if (res.state === 'recognised') {
      const c = res.canonical;
      md.push('Canonical (' + c.utteranceType + ', cost ' + c.cost.toFixed(2) + '): `' + c.bracket + '`', '', 'Roles: ' + fmtRoles(c), '');
      const others = res.readings.slice(1, 4);
      for (const o of others) md.push('- ' + o.id + ' (' + o.utteranceType + ', cost ' + o.cost.toFixed(2) + '): `' + o.bracket + '`');
      if (others.length) md.push('');
      if (res.choicePoints && res.choicePoints.length) md.push('Choice points: ' + res.choicePoints.map(c => c.word + ' {' + c.options.join(', ') + '}').join('; '), '');
    }
    if (res.conflicts) md.push('Conflict: ' + res.conflicts.map(c => c.constraint + ' at “' + c.text + '” (' + c.explanation + ')').join('; '), '');
    if (res.partial && res.state !== 'recognised') md.push('Partial: ' + res.partial.map(x => (x.cat ? '[' + x.cat + ' ' + x.text + ']' : x.text)).join(' '), '');
    if (res.state === 'invalid_tiles') md.push('Tiles: ' + (res.reason || '') + ' ' + JSON.stringify(res.words || res.word || ''), '');
    if (!ok) md.push('**Failures:** ' + r.failures.join('; '), '');
  }
  md.splice(2, 0, `**${pass}/${P.length} probes pass.**`, '');
  fs.mkdirSync(path.join(__dirname, '..', 'reports'), {recursive: true});
  if (!process.env.WL_NO_WRITE) fs.writeFileSync(path.join(__dirname, '..', 'reports', 'probe_analyses.md'), md.join('\n'));
  for (const r of out) console.log((r.failures.length ? 'FAIL ' : 'ok   ') + r.p.id.padEnd(4) + ' ' + r.res.state.padEnd(12) + (r.failures.length ? ' ' + r.failures.join('; ') : ''));
  console.log(`\n${pass}/${P.length} pass`);
  return {pass, fail};
}
if (require.main === module) { const {fail} = main(); process.exitCode = fail ? 1 : 0; }
module.exports = {main, runProbe};
