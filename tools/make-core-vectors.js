#!/usr/bin/env node
/*
  tools/make-core-vectors.js — writes spec/core-profile-v1-vectors.json from the
  reference decoder: each vector's link, the spec's expectation, and the
  reference decoder's full output. Every implementation (the npm and PyPI
  packages) must reproduce "decoded" and "annotations" exactly.
    node tools/make-core-vectors.js            write the file
    node tools/make-core-vectors.js --check    exit 1 if the file is out of date
*/
'use strict';
const fs = require('fs'), path = require('path');
const R = require(path.join(__dirname, '..', 'spec', 'core-profile-v1-reference.js'));
const out = {
  profile: 'Geosonify core profile v1', spec: 'spec/CORE-PROFILE-V1.md',
  note: 'Generated by tools/make-core-vectors.js from spec/core-profile-v1-reference.js. Coordinates are [latitude, longitude] in degrees.',
  vectors: R.VECTORS.map(([q, want]) => ({ link: q, want, decoded: R.decodeLink(q), annotations: R.parseAnnotations(q) }))
};
const text = JSON.stringify(out, null, 1) + '\n';
const file = path.join(__dirname, '..', 'spec', 'core-profile-v1-vectors.json');
if (process.argv.includes('--check')) {
  const same = fs.existsSync(file) && fs.readFileSync(file, 'utf8') === text;
  console.log(same ? 'PASS vectors file up to date' : 'FAIL spec/core-profile-v1-vectors.json is out of date: run node tools/make-core-vectors.js');
  process.exit(same ? 0 : 1);
}
fs.writeFileSync(file, text);
console.log('wrote ' + path.relative(process.cwd(), file) + ' (' + out.vectors.length + ' vectors)');
